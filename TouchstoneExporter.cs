using System.Globalization;
using System.Text;

namespace RfSimulator;

public static class TouchstoneExporter
{
    public static void WriteS2P(string fileName, IReadOnlyList<SParameterPoint> sweep, double z0 = 50, string? metadata = null)
    {
        var builder = new StringBuilder();
        builder.AppendLine($"# MHz S RI R {z0.ToString("G17", CultureInfo.InvariantCulture)}");
        if (metadata is not null) builder.AppendLine("! " + metadata.Replace("\r", " ").Replace("\n", " "));
        builder.AppendLine("! Generated by RF LC Structure Simulator");
        builder.AppendLine("! freq_MHz S11_real S11_imag S21_real S21_imag S12_real S12_imag S22_real S22_imag");

        foreach (var point in sweep)
        {
            builder.Append((point.FrequencyHz / 1e6).ToString("G17", CultureInfo.InvariantCulture));
            AppendComplex(builder, point.S11);
            AppendComplex(builder, point.S21);
            AppendComplex(builder, point.S12);
            AppendComplex(builder, point.S22);
            builder.AppendLine();
        }

        File.WriteAllText(fileName, builder.ToString());
    }

    private static void AppendComplex(StringBuilder builder, System.Numerics.Complex value)
    {
        builder.Append(' ');
        builder.Append(value.Real.ToString("G17", CultureInfo.InvariantCulture));
        builder.Append(' ');
        builder.Append(value.Imaginary.ToString("G17", CultureInfo.InvariantCulture));
    }
}
